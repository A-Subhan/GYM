  Ntn: Joi.string().max(20).allow('', null).optional(),
  Strn: Joi.string().max(20).allow('', null).optional(),
  BankName: Joi.string().max(150).allow('', null).optional(),
  BankAccountTitle: Joi.string().max(150).allow('', null).optional(),
