const coaStructureSchema = Joi.object({
  Levels: Joi.array().items(Joi.number().integer().min(1).max(12)).min(1).max(7).required()
    .custom((value, helpers) => {
      const total = value.reduce((s, d) => s + d, 0);
      if (total > 12) return helpers.error('any.invalid');
      return value;
    }, 'total digits rule')
    .message({ 'any.invalid': 'COA structure cannot exceed 12 total digits.' }),
});

