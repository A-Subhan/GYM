/* ================================================================== */
/* VOUCHER DOCUMENTS                                                  */
/* CASH / BANK: header money account + Amount-only lines — the        */
/* engine derives Debit/Credit from the direction.                    */
/* JOURNAL / OTB: explicit Debit / Credit lines; must balance.        */
/* ================================================================== */

const simpleLineSchema = Joi.object({
  AccountID: Joi.number().integer().positive().required(),
  Description: Joi.string().max(500).allow('', null).optional(),
  Amount: Joi.number().precision(2).greater(0).required()
    .messages({ 'number.greater': 'Every line amount must be greater than zero.' }),
  TaxHeadID: Joi.number().integer().positive().allow(null).optional(),
  TaxAccountID: Joi.number().integer().positive().allow(null).optional(),
  TaxPercent: Joi.number().precision(4).min(0).max(100).allow(null).optional(),
  TaxAmount: Joi.number().precision(2).min(0).allow(null).optional(),
  ChequeNo: Joi.string().max(50).allow('', null).optional(),
  ChequeStatus: Joi.string().valid('Hold', 'Pending', 'Cleared', 'Bounced', 'Cancelled').allow(null, '').optional(),
  ChequeTitle: Joi.string().max(150).allow('', null).optional(),
  ReferenceNo: Joi.string().max(50).allow('', null).optional(),
  KnockOff: Joi.boolean().default(false),
  BillRef: Joi.string().max(50).allow('', null).optional(),
  BillDate: Joi.date().allow(null).optional(),
  DueDate: Joi.date().allow(null).optional(),
  PartyMemberID: Joi.number().integer().positive().allow(null).optional(),
  PartySupplierID: Joi.number().integer().positive().allow(null).optional(),
  PartyStaffID: Joi.number().integer().positive().allow(null).optional(),
}).custom((value, helpers) => {
  // a user must not inject ledger sides through a simple voucher
  if (value.Debit !== undefined || value.Credit !== undefined) return helpers.error('any.invalid');
  // tax rule: percent/amount present => TaxAccountID mandatory (Rule: Part 8)
  const pct = Number(value.TaxPercent || 0);
  const amt = Number(value.TaxAmount || 0);
  if ((pct > 0 || amt > 0) && !value.TaxAccountID) return helpers.error('any.invalid');
  return value;
}, 'simple line rule').message({
  'any.invalid': 'Debit/Credit are automatic for Cash and Bank vouchers — send Amount only. Tax Account is mandatory when tax percentage or tax amount is used.',
});

const balancedLineSchema = Joi.object({
  AccountID: Joi.number().integer().positive().required(),
  Description: Joi.string().max(500).allow('', null).optional(),
  Debit: Joi.number().precision(2).min(0).default(0),
  Credit: Joi.number().precision(2).min(0).default(0),
}).custom((value, helpers) => {
  const d = value.Debit || 0;
  const c = value.Credit || 0;
  if (d > 0 && c > 0) return helpers.error('any.invalid');
  if (d === 0 && c === 0) return helpers.error('any.invalid');
  return value;
}, 'balanced line rule').message({
  'any.invalid': 'Each line must have exactly one of Debit or Credit, greater than zero.',
});

const documentSchema = Joi.object({
  Family: Joi.string().valid('CASH', 'BANK', 'JOURNAL', 'OTB').required(),
  Status: Joi.string().valid('Posted', 'Draft', 'Hold').default('Posted'),
  Direction: Joi.string().valid('Receipt', 'Payment')
    .when('Family', { is: 'CASH', then: Joi.required() })
    .when('Family', { is: 'BANK', then: Joi.required() })
    .when('Family', { is: 'JOURNAL', then: Joi.valid(null) })
    .when('Family', { is: 'OTB', then: Joi.valid(null) }),
  MoneyAccountID: Joi.number().integer().positive()
    .when('Family', { is: 'CASH', then: Joi.required() })
    .when('Family', { is: 'BANK', then: Joi.required() })
    .when('Family', { is: 'JOURNAL', then: Joi.valid(null) })
    .when('Family', { is: 'OTB', then: Joi.valid(null) }),
  VoucherDate: Joi.date().required(),
  BranchID: Joi.number().integer().positive().allow(null).optional(),
  Narrative: Joi.string().max(200).allow('', null).optional()
    .messages({ 'string.max': 'Voucher description cannot exceed 200 characters.' }),
  Lines: Joi.array()
    .when('Family', {
      is: 'CASH', then: Joi.array().items(simpleLineSchema).min(1).required(),
    })
    .when('Family', {
      is: 'BANK', then: Joi.array().items(simpleLineSchema).min(1).required(),
    })
    .when('Family', {
      is: 'JOURNAL', then: Joi.array().items(balancedLineSchema).min(2).required(),
    })
    .when('Family', {
      is: 'OTB', then: Joi.array().items(balancedLineSchema).min(2).required(),
    }),
}).messages({
  'array.min': 'Add at least one detail line (a journal / opening voucher needs at least two).',
});

